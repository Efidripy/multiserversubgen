import { cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
const mocks = vi.hoisted(() => ({ get: vi.fn(), update: vi.fn() }));
vi.mock('../src/api/serverOps', () => ({ getXrayTemplate: mocks.get, updateXrayTemplate: mocks.update }));
vi.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string, options?: { number?: number }) => options?.number ? `${key} ${options.number}` : key }) }));
vi.mock('../src/components/LazyJsonEditor', () => ({ LazyJsonEditor: ({ value, onChange, label }: any) => <textarea aria-label={label} value={value} onChange={(e) => onChange?.(e.target.value)} /> }));
import { XrayTemplateEditor } from '../src/components/XrayTemplateEditor';
afterEach(() => { cleanup(); vi.clearAllMocks(); });
it('edits routing rules locally and saves exact routing and expected values', async () => {
  const api = { type: 'field', inboundTag: ['api'], outboundTag: 'api' };
  const a = { type: 'field', domain: ['a'], outboundTag: 'direct', extra: 42 };
  const b = { type: 'field', ip: ['b'], outboundTag: 'block' };
  const original = { domainStrategy: 'AsIs', balancers: [{ tag: 'x' }], rules: [api, a, b] };
  mocks.get.mockResolvedValue({ routing: original }); mocks.update.mockResolvedValue({});
  vi.spyOn(window, 'confirm').mockReturnValue(true);
  render(<XrayTemplateEditor nodeId={4} section="routing" />);
  await screen.findByText('a');
  const rows = screen.getAllByRole('row');
  expect((within(rows[1]).getByRole('checkbox') as HTMLInputElement).disabled).toBe(true);
  expect((within(rows[1]).getByRole('button', { name: 'common.delete' }) as HTMLButtonElement).disabled).toBe(true);
  expect((within(rows[1]).getByRole('button', { name: 'common.edit' }) as HTMLButtonElement).disabled).toBe(true);
  expect((screen.getByLabelText('nodeOps.moveUp 2') as HTMLButtonElement).disabled).toBe(true);
  fireEvent.click(screen.getByLabelText('nodeOps.moveUp 3'));
  fireEvent.click(screen.getByLabelText('nodeOps.enableRule 3'));
  fireEvent.click(within(screen.getAllByRole('row')[2]).getByRole('button', { name: 'common.delete' }));
  fireEvent.click(screen.getByText('nodeOps.addRule'));
  fireEvent.change(screen.getByLabelText('nodeOps.ruleEditor'), { target: { value: '{"type":"field","outboundTag":"new","network":"tcp"}' } });
  fireEvent.click(screen.getByText('common.save'));
  fireEvent.click(screen.getByText('nodeOps.saveApply'));
  await waitFor(() => expect(mocks.update).toHaveBeenCalledWith(4, 'routing', { ...original, rules: [api, { ...a, enabled: false }, { type: 'field', outboundTag: 'new', network: 'tcp' }] }, original));
});
it('protects the api rule in JSON and prevents switching on invalid JSON', async () => {
  const api = { inboundTag: ['api'], outboundTag: 'api' };
  mocks.get.mockResolvedValue({ routing: { rules: [api] } });
  render(<XrayTemplateEditor nodeId={4} section="routing" />);
  await screen.findByLabelText('nodeOps.enableRule 1');
  fireEvent.click(screen.getByText('JSON'));
  const input = screen.getByLabelText('nodeOps.template');
  fireEvent.change(input, { target: { value: '{' } });
  expect((screen.getByText('nodeOps.table') as HTMLButtonElement).disabled).toBe(true);
  fireEvent.change(input, { target: { value: '{"rules":[]}' } });
  expect((screen.getByText('nodeOps.saveApply') as HTMLButtonElement).disabled).toBe(true);
  expect(screen.getByText('nodeOps.protectedRule')).toBeTruthy();
});
