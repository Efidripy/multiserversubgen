artifact_digest() {
    local component="$1"
    local arch="$2"
    local variable="ARTIFACT_${component}_${arch^^}_SHA256"
    printf '%s' "${!variable:-}"
}

artifact_verify_file() {
    local component="$1"
    local arch="$2"
    local file_path="$3"
    local expected
    expected="$(artifact_digest "$component" "$arch")"
    [[ -n "$expected" ]] && printf '%s  %s\n' "$expected" "$file_path" | sha256sum -c - >/dev/null
}
